#include <iostream>
using namespace std;
/*
	 &有0必0
*/

int main()
{
	//1.位与运算的定义
	int a = 0b1010;  //10
	int b = 0b0110; //6
		//      0b0010
	cout << (a & b) << endl;
	cout << "——" << endl;

	//2.奇偶性
	cout << 5 % 2 << endl;  //优先级高，效率低
	cout << (5 & 1) << endl;  //优先级低，效率高
	cout << "——" << endl;
	//0b101
	//0b001   0b001所以是奇数

	//3.获取一个数二进制的后五位
	int c = 0b1001001001;  //01001
	cout << (c & 0b11111) << endl;
	cout << "——" << endl;

	//4.将末5位归0
	int d = 0b11111111111111111111111111100000;
	cout << (c & d) << endl;
	cout << "——" << endl;

	//5.消除末尾连续的1
	int e = 0b10000000010111111;
	//e+1 = 0b10000000011000000	
	  //&   0b10000000010000000
	cout << (e & (e + 1)) << endl;

	//6.2的幂判定
	int f = 0b100000000;
	//f-1 = 0b011111111
	//&  =  0b000000000
	//(f & (f - 1))==0 && (f>0)
	return 0;
}